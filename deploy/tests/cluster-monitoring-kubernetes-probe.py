#!/usr/bin/env python3
"""Assert live Kubernetes monitoring APIs; never substitute synthetic metrics.

Run against the disposable stack generated by the prepare script, with explicit
kubectl port-forwards for app and Prometheus. Credentials stay in the 0600
artifacts directory. Each stage appends redacted JSON evidence. A non-zero exit
means one or more live assertions failed; no cloud certification is implied.
"""
import argparse,json,pathlib,urllib.request,urllib.parse,urllib.error,time,sys,subprocess
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--artifacts-dir',required=True)
p.add_argument('--stage',choices=['baseline','scale','traffic','unknown','recovered','uid','oom','alert-create','alert-fired','alert-held','alert-resolved'],required=True)
p.add_argument('--kubeconfig',help='Explicit disposable cluster kubeconfig; required for traffic stage')
p.add_argument('--app-url',default='http://127.0.0.1:18080')
p.add_argument('--prometheus-url',default='http://127.0.0.1:19090')
p.add_argument('--expected-crash',type=int,choices=[0,1],default=1);p.add_argument('--alert-metric',choices=['pod_crash_loop','pod_ready'],default='pod_crash_loop');p.add_argument('--namespace',default='monitoring-acceptance');p.add_argument('--cluster-label',default='acceptance-k3s');p.add_argument('--timeout',type=int,default=120)
a=p.parse_args();root=pathlib.Path(a.artifacts_dir)
for u in (a.app_url,a.prometheus_url):
 if urllib.parse.urlparse(u).hostname not in ('localhost','127.0.0.1','::1'):p.error('loopback port-forward URLs required')
secrets=json.loads((root/'credentials.json').read_text());token=None

def request(path,body=None,prom=False):
 url=(a.prometheus_url if prom else a.app_url)+path;headers={}
 if token and not prom:headers['Authorization']='Bearer '+token
 if body is not None:headers['Content-Type']='application/json'
 try:
  with urllib.request.urlopen(urllib.request.Request(url,data=None if body is None else json.dumps(body).encode(),headers=headers),timeout=20) as r:return json.load(r)
 except urllib.error.HTTPError as e:
  raise RuntimeError(str(e.code)+' '+e.read(4096).decode(errors='replace')) from None
login=request('/api/v1/auth/login',{'email':'audit@example.test','password':secrets['admin_password']});token=login['data']['access_token']
checks=[]
def check(name,fn,timeout=None):
 until=time.monotonic()+(a.timeout if timeout is None else timeout);last=None
 while True:
  try:ok,last=fn()
  except Exception as e:ok=False;last={'error':str(e)}
  if ok or time.monotonic()>=until:break
  time.sleep(5)
 checks.append({'name':name,'passed':bool(ok),'observed_at':time.strftime('%Y-%m-%dT%H:%M:%SZ',time.gmtime()),'evidence':last});print(('PASS ' if ok else 'FAIL ')+name,flush=True)
def query(metric,**kw):
 return request('/api/v1/admin/ops/monitoring/query?'+urllib.parse.urlencode({'metric':metric,'cluster':a.cluster_label,'namespace':a.namespace,'window':'1m','min_requests':1,**kw}))['data']
def prom(q):return request('/api/v1/query?'+urllib.parse.urlencode({'query':q}),prom=True)['data']['result']
def points(q):return [(s['labels'],v) for s in q.get('series',[]) for v in s.get('points',[])]
def value(metric,expected=None,pod=None,**kw):
 q=query(metric,**({'pod':pod} if pod else {}),**kw);v=[v['value'] for _,v in points(q) if v.get('value') is not None]
 return (bool(v) and (expected is None or any(abs(x-expected)<max(1e-7,abs(expected)*1e-6) for x in v)),q)
def state(metric,expected,pod=None,**kw):
 q=query(metric,**({'pod':pod} if pod else {}),**kw);return q['state']==expected,q
if a.stage=='baseline':
 check('kubernetes_capabilities',lambda:((d:=request('/api/v1/admin/ops/monitoring/capabilities')['data']).get('kubernetes_resources') is True,d))
 check('four_real_scrape_jobs_healthy',lambda:((d:=prom('min by (job) (up)')) and len(d)>=4 and all(float(x['value'][1])==1 for x in d),d))
 for pod,cpu,memory in [('ordinary',.25,64*1024**2),('init-sidecar',.6,128*1024**2),('pod-level',1.2,256*1024**2),('with-overhead',.55,112*1024**2)]:
  check(pod+'_cpu_effective_limit',lambda pod=pod,cpu=cpu:value('pod_cpu_limit_cores',cpu,pod))
  check(pod+'_memory_effective_limit',lambda pod=pod,memory=memory:value('pod_memory_limit_bytes',memory,pod))
 check('unlimited_is_not_applicable',lambda:state('pod_memory_limit_bytes','NotApplicable','unlimited'))
 check('real_cadvisor_memory',lambda:value('pod_memory_bytes',pod='ordinary'))
 check('real_cadvisor_cpu',lambda:value('pod_cpu_cores',pod='ordinary'))
 check('hpa_target_cpu_utilization',lambda:value('hpa_target_cpu_utilization_percent',50))
 check('crash_loop_observed',lambda:value('pod_crash_loop',a.expected_crash,'crash-recovery'))
 q=query('pod_info',pod='ordinary');(root/'ordinary-baseline.json').write_text(json.dumps(q,indent=2))
elif a.stage=='scale':
 check('deployment_scaled_to_three',lambda:value('deployment_desired_replicas',3,deployment='modurelay'))
 check('deployment_three_ready',lambda:value('deployment_ready_replicas',3,deployment='modurelay'))
 check('three_distinct_instance_targets',lambda:((d:=prom('count(up{job="modurelay-instance"} == 1)')) and float(d[0]['value'][1])==3,d))
 for kind in ['Deployment','HorizontalPodAutoscaler']:
  check(kind+'_events_archived',lambda kind=kind:((d:=request('/api/v1/admin/ops/monitoring/events?'+urllib.parse.urlencode({'cluster':a.cluster_label,'namespace':a.namespace,'object_kind':kind}))) and len(d['data'].get('events',[]))>0,d))
elif a.stage=='traffic':
 if not a.kubeconfig:p.error('--kubeconfig is required for traffic')
 context=subprocess.check_output(['kubectl','--kubeconfig',a.kubeconfig,'config','current-context'],text=True).strip()
 if not context.startswith(('k3d-modurelay-monitoring-','kind-modurelay-monitoring-')):p.error('traffic requires an owned disposable monitoring cluster context')
 # Let the successful admin login reach the 10s scrape before establishing
 # the traffic baseline. Run this stage without concurrent login probes.
 time.sleep(15)
 raw='sum(modurelay_http_requests_total{source="app",route="other",method="POST",status_code="200"})';before=prom(raw);n0=float(before[0]['value'][1]) if before else 0
 subprocess.run(['kubectl','--kubeconfig',a.kubeconfig,'-n',a.namespace,'exec','deployment/redis','--','sh','-c','for i in $(seq 1 90); do wget -q -O /dev/null --header="Content-Type: application/json" --post-data="{}" http://modurelay-metrics:8080/api/event_logging/batch || exit 1; done'],check=True)
 def counter_delta():
  after=prom(raw);perpod=prom('sum by (pod,uid) (modurelay_http_requests_total{source="app",route="other",method="POST",status_code="200"})');delta=float(after[0]['value'][1])-n0 if after else None
  return delta==90 and len(perpod)==3,{'sent':90,'before':before,'after':after,'delta':delta,'per_pod':perpod}
 check('ninety_requests_conserved_across_three_pods',counter_delta)
elif a.stage=='unknown':check('failed_ksm_cannot_manufacture_recovery',lambda:state('pod_crash_loop','Unknown','crash-recovery'))
elif a.stage=='recovered':check('same_uid_crash_loop_recovers_zero',lambda:value('pod_crash_loop',0,'crash-recovery'))
elif a.stage=='uid':
 old=json.loads((root/'ordinary-baseline.json').read_text());uid=old['series'][0]['labels']['uid']
 check('old_uid_has_no_current_limit',lambda:state('pod_cpu_limit_cores','Unknown','ordinary',uid=uid))
 check('replacement_has_current_limit',lambda:value('pod_cpu_limit_cores',.25,'ordinary'))
 check('pod_uid_changed',lambda:((d:=query('pod_info',pod='ordinary')) and len(d.get('series',[]))==1 and d['series'][0]['labels'].get('uid')!=uid,d))
elif a.stage=='oom':
 check('real_oom_laststate',lambda:value('pod_oom',1,'oom-restart'))
 check('real_restart_increase',lambda:((d:=query('pod_restarts',pod='oom-restart')) and any(v.get('value',0)>0 for _,v in points(d) if v.get('value') is not None),d))
 check('real_oom_counter_increase',lambda:((d:=query('pod_oom_count',pod='oom-restart')) and any(v.get('value',0)>0 for _,v in points(d) if v.get('value') is not None),d))
elif a.stage=='alert-create':
 body={'name':'Disposable CrashLoop Acceptance','description':'Isolated local Kubernetes acceptance','enabled':True,'severity':'P2','metric_type':a.alert_metric,'operator':'<' if a.alert_metric=='pod_ready' else '>','threshold':1 if a.alert_metric=='pod_ready' else 0,'window_minutes':1,'sustained_minutes':1,'cooldown_minutes':1,'min_requests':0,'notify_email':False,'filters':{'cluster':a.cluster_label,'namespace':a.namespace,'pod':'crash-recovery'}}
 result=request('/api/v1/admin/ops/alert-rules',body)['data'];(root/'crash-alert-rule.json').write_text(json.dumps(result,indent=2));check('alert_rule_created',lambda:(bool(result.get('id')),result),0)
else:
 rule=json.loads((root/'crash-alert-rule.json').read_text());expected='resolved' if a.stage=='alert-resolved' else 'firing'
 def alert_event():
  d=request('/api/v1/admin/ops/alert-events?limit=100')['data'];events=d if isinstance(d,list) else d.get('events',d.get('items',[]));matching=[x for x in events if x.get('rule_id')==rule['id']]
  if a.stage=='alert-held':
   rules=request('/api/v1/admin/ops/alert-rules')['data'];current=next((r for r in rules if r['id']==rule['id']),{})
   return any(x['status']==expected for x in matching) and current.get('data_status')=='unavailable',{'events':matching,'rule':current}
  return any(x['status']==expected for x in matching),matching
 check(a.stage,alert_event)
out=root/('live-'+a.stage+'.json')
if out.exists():out.rename(root/('live-'+a.stage+'-previous-'+str(time.time_ns())+'.json'))
out.write_text(json.dumps({'stage':a.stage,'source':'live Kubernetes/application/Prometheus APIs','checks':checks},indent=2));sys.exit(0 if all(x['passed'] for x in checks) else 1)
